const DEG_NAMES_BY_LANG = {
  ko: ["도", "레", "미", "파", "솔", "라", "시"],
  en: ["Do", "Re", "Mi", "Fa", "Sol", "La", "Ti"],
  ja: ["ド", "レ", "ミ", "ファ", "ソ", "ラ", "シ"],
};

// 키 이름 (장조·단조, 으뜸음 0=C … 11=B)
const PITCH_NAMES = ["C", "C♯", "D", "E♭", "E", "F", "F♯", "G", "A♭", "A", "B♭", "B"];
const KEY_WORDS = {
  ko: { major: ["다장조", "", "라장조", "", "마장조", "바장조", "", "사장조", "", "가장조", "", "나장조"], minor: ["다단조", "", "라단조", "", "마단조", "바단조", "", "사단조", "", "가단조", "", "나단조"], maj: "장조", min: "단조" },
  en: { maj: "major", min: "minor" },
  ja: { major: ["ハ長調", "", "ニ長調", "", "ホ長調", "ヘ長調", "", "ト長調", "", "イ長調", "", "ロ長調"], minor: ["ハ短調", "", "ニ短調", "", "ホ短調", "ヘ短調", "", "ト短調", "", "イ短調", "", "ロ短調"], maj: "長調", min: "短調" },
};

const LANGS = [
  { code: "ko", label: "한국어" },
  { code: "en", label: "English" },
  { code: "ja", label: "日本語" },
];
const LANG_KEY = "dcinvox.lang";

let LANG = (() => {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && I18N[saved]) return saved;
  } catch {
    // 저장소를 못 쓰면 컴퓨터 언어
  }
  const sys = (navigator.language || "en").toLowerCase();
  return sys.startsWith("ko") ? "ko" : sys.startsWith("ja") ? "ja" : "en";
})();

function t(key, vars) {
  let s = I18N[LANG]?.[key] ?? I18N.en[key] ?? I18N.ko[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

function degNames() {
  return DEG_NAMES_BY_LANG[LANG] ?? DEG_NAMES_BY_LANG.en;
}

/// 키 이름: 장조면 "C major" / "다장조(C)" / "ハ長調(C)"
function keyName(root, minor = false) {
  const p = PITCH_NAMES[((root % 12) + 12) % 12];
  const w = KEY_WORDS[LANG] ?? KEY_WORDS.en;
  if (LANG === "en") return `${p} ${minor ? w.min : w.maj}`;
  const word = (minor ? w.minor : w.major)?.[((root % 12) + 12) % 12];
  return word ? `${word}(${p}${minor ? "m" : ""})` : `${p}${minor ? w.min : w.maj}`;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll("[data-i18n]")) el.innerHTML = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
}

// 언어를 바꾸면 화면 전체를 다시 그리도록 알림
const langListeners = [];
function onLanguageChange(fn) {
  langListeners.push(fn);
}

function setLanguage(code) {
  if (!I18N[code]) return;
  LANG = code;
  try {
    localStorage.setItem(LANG_KEY, code);
  } catch {
    // 이번 실행 동안만 유지
  }
  applyI18n();
  // 백엔드 오류 메시지도 같은 언어로
  window.__TAURI__?.core.invoke("set_language", { lang: code }).catch(() => {});
  langListeners.forEach((fn) => fn());
}
